"""Иерархия исключений qsim.

До этого модуля все ошибки валидации бросались как обычные TypeError/
ValueError, из-за чего вызывающий код не мог программно отличить,
например, ошибку неверного индекса кубита от ошибки неверного числа
shots, не разбирая текст сообщения.

Здесь введена единая иерархия с корнем ``QSimError``. Каждое исключение
qsim, связанное с некорректным *значением*, одновременно является и
``QSimError`` (для перехвата «любой ошибки qsim»), и ``ValueError``
(через ``QSimValueError``) — а связанное с некорректным *типом*
аргумента — и ``QSimError``, и ``TypeError`` (через ``QSimTypeError``).
Благодаря множественному наследованию весь существующий код и тесты,
полагающиеся на ``assertRaises(TypeError)``/``assertRaises(ValueError)``,
продолжают работать без единого изменения — это чистое уточнение типов
исключений, а не breaking change.
"""
from __future__ import annotations


class QSimError(Exception):
    """Базовое исключение для всех ошибок qsim.

    Ловите этот класс, если нужно перехватить любую ошибку, порождённую
    qsim, не заботясь о том, TypeError она или ValueError.
    """


class QSimTypeError(QSimError, TypeError):
    """Некорректный тип аргумента (унаследовано и от builtins.TypeError,
    так что старый ``except TypeError`` продолжает работать)."""


class QSimValueError(QSimError, ValueError):
    """Некорректное значение аргумента (унаследовано и от
    builtins.ValueError, так что старый ``except ValueError`` продолжает
    работать)."""


class QubitError(QSimValueError):
    """Проблема со спецификацией кубитов: индекс вне диапазона, число
    кубитов схемы/состояния некорректно, повторяющиеся или пересекающиеся
    control/target-кубиты и т.п."""


class GateError(QSimValueError):
    """Проблема с гейтом: неверная форма матрицы, матрица неунитарна,
    неизвестное имя встроенного гейта."""


class ShotsError(QSimValueError):
    """Некорректное значение shots (отрицательное и т.п.)."""


class CircuitError(QSimValueError):
    """Ошибка на уровне построения/запуска/экспорта схемы, не сводящаяся
    к конкретному кубиту, гейту или shots — например, попытка запустить
    схему с несвязанным Parameter, или экспортировать в QASM инструкцию,
    для которой нет прямого соответствия в целевом формате."""
